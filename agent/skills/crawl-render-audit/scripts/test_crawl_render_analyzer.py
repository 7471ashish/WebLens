@pytest.mark.asyncio
async def test_21_navigation_timeout_fallback():
    """21. Test handling of navigation timeout with partial DOM extraction."""
    async with async_playwright() as p:
        browser = await p.chromium.launch(headless=True, args=["--no-sandbox"])
        context = await browser.new_context()
        page = await context.new_page()

        async def slow_route(route):
            await asyncio.sleep(0.5)
            await route.fulfill(status=200, body="<html><body>Slow</body></html>", content_type="text/html")

        await page.route("https://example.com/slow", slow_route)

        res = await analyze_rendered_page("https://example.com/slow", options={"navigation_timeout_ms": 100}, page_instance=page)
        await context.close()
        await browser.close()

    assert res["rendering"]["status"] in ("partial", "browser_error", "navigation_error")


