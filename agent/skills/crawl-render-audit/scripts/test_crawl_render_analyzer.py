@pytest.mark.asyncio
async def test_31_browser_launch_failure_handling():
    """31. Test that launch errors (e.g. missing Chromium binary) result in browser_launch_failure status."""
    from unittest.mock import AsyncMock, patch

    mock_playwright_ctx = AsyncMock()
    mock_playwright_ctx.chromium.launch.side_effect = Exception("Executable doesn't exist at /root/.cache/ms-playwright/chromium/chrome")

    with patch("render_analyzer.async_playwright") as mock_pw_factory:
        mock_pw_factory.return_value.start = AsyncMock(return_value=mock_playwright_ctx)
        res = await analyze_rendered_page("https://example.com")

    assert res["rendering"]["status"] == "browser_launch_failure"
    assert len(res["errors"]) == 1
    assert res["errors"][0]["type"] == "launch_error"
    assert "Executable doesn't exist" in res["errors"][0]["message"]


@pytest.mark.asyncio
async def test_32_browser_render_crash_handling():
    """32. Test that mid-render crashes result in browser_error status."""
    from unittest.mock import AsyncMock, MagicMock

    mock_page = MagicMock()
    mock_page.goto = AsyncMock(side_effect=Exception("Page crashed: Target crashed while loading JS bundle"))

    res = await analyze_rendered_page("https://example.com", page_instance=mock_page)

    assert res["rendering"]["status"] == "browser_error"
    assert len(res["errors"]) == 1
    assert res["errors"][0]["type"] == "render_error"
    assert "Page crashed" in res["errors"][0]["message"]

