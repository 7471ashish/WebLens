@pytest.mark.asyncio
async def test_1_basic_static_html():
    """1. Test basic static HTML rendering."""
    async with async_playwright() as p:
        browser = await p.chromium.launch(headless=True, args=["--no-sandbox"])
        context = await browser.new_context()
        page = await context.new_page()

        html = "<html><head><title>Static Page</title></head><body><h1>Hello Static</h1><p>Welcome to static page</p></body></html>"
        await page.route("https://example.com/test", lambda route: route.fulfill(status=200, body=html, content_type="text/html"))

        res = await analyze_rendered_page("https://example.com/test", options={"wait_after_load_ms": 0}, page_instance=page)
        await context.close()
        await browser.close()

    assert res["rendering"]["status"] == "success"
    assert res["title"]["value"] == "Static Page"
    assert res["headings"]["h1_text"] == ["Hello Static"]
    assert res["text_content"]["visible_word_count"] > 0


