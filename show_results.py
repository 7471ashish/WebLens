import httpx
import json

job_id = "92996cc5-ef67-470a-ad2b-667e4d021368"
resp = httpx.get(f"http://127.0.0.1:8001/audits/{job_id}")
data = resp.json()
result = data.get("result", {})

print("\n" + "=" * 60)
print(f"       WEBLENS AUDIT REPORT: {result.get('site')}")
print("=" * 60)
print(f"Audited At : {result.get('audited_at')}")
print(f"Runtime    : {result.get('meta', {}).get('runtime_seconds', 'N/A')}s")
print(f"Pages      : {result.get('meta', {}).get('pages_crawled', 0)} crawled, {result.get('meta', {}).get('pages_discovered', 0)} discovered")
print(f"Types      : {', '.join(result.get('meta', {}).get('page_types_covered', []))}")
print("-" * 60)
print("SUMMARY FINDINGS COUNTS:")
summary = result.get("summary", {})
print(f"  • Total Findings : {summary.get('total_findings')}")
print(f"  • Critical       : {summary.get('critical')}")
print(f"  • High           : {summary.get('high')}")
print(f"  • Medium         : {summary.get('medium')}")
print(f"  • Low            : {summary.get('low')}")
print("-" * 60)
print("COVERAGE:")
coverage = result.get("coverage", {})
print(f"  • Skills Run : {coverage.get('skills_run')}/5")
print(f"  • Skills OK  : {coverage.get('skills_ok')}/5")
print("-" * 60)
print(f"TOP FINDINGS (Displaying first 6 of {len(result.get('findings', []))}):")
for idx, finding in enumerate(result.get("findings", [])[:6], 1):
    sev = finding.get("severity", "info").upper()
    fid = finding.get("id")
    title = finding.get("title")
    tier = finding.get("evidence_tier", "tier_1")
    action = finding.get("suggested_action", {}).get("summary", "")
    print(f"\n[{idx}] [{sev}] {fid}")
    print(f"    Title : {title}")
    print(f"    Tier  : {tier} ({'Measured' if tier in ('tier_1', 'tier_2') else 'Heuristic'})")
    print(f"    Action: {action}")
print("\n" + "=" * 60)
